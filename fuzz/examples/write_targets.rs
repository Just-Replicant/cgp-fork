//! Regenerate one cargo-fuzz target per macro entrypoint, from the registry in
//! `cgp-fork-macro-impl`:
//!
//! `cargo run --manifest-path fuzz/Cargo.toml --example write_targets`
//!
//! Writes `fuzz_targets/<target>.rs` for each entrypoint, removes targets whose
//! entrypoint is gone, and rewrites the generated `[[bin]]` section of
//! `Cargo.toml`. The `registry_tests` in `cgp-fork-macro-impl` fail when this is
//! out of date.
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use cgp_fork_macro_fuzz::{entrypoints, fuzz_target_name};

const BEGIN: &str = "# BEGIN generated targets (examples/write_targets.rs)";
const END: &str = "# END generated targets";

fn main() -> std::io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let targets_dir = root.join("fuzz_targets");

    let mut wanted = Vec::new();
    for (name, _) in entrypoints() {
        let target = fuzz_target_name(name);
        let source = format!(
            "//! Fuzz the `{name}` entrypoint. Generated by `examples/write_targets.rs`; do not edit.\n\
             #![no_main]\n\
             \n\
             libfuzzer_sys::fuzz_target!(|data: &[u8]| {{\n    \
             cgp_fork_macro_fuzz::run_entrypoint(\"{name}\", data);\n\
             }});\n"
        );
        fs::write(targets_dir.join(format!("{target}.rs")), source)?;
        wanted.push(target);
    }

    for entry in fs::read_dir(&targets_dir)? {
        let path = entry?.path();
        let stem = path
            .file_stem()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        if stem != "entrypoints" && !wanted.contains(&stem) {
            fs::remove_file(&path)?;
        }
    }

    let mut section = String::new();
    for target in &wanted {
        write!(
            section,
            "\n[[bin]]\nname  = \"{target}\"\npath  = \"fuzz_targets/{target}.rs\"\ntest  = false\ndoc   = false\nbench = false\n"
        )
        .expect("writing to a String cannot fail");
    }

    let manifest_path = root.join("Cargo.toml");
    let manifest = fs::read_to_string(&manifest_path)?;
    let (head, rest) = manifest
        .split_once(BEGIN)
        .expect("Cargo.toml has the generated-targets marker");
    let (_, tail) = rest.split_once(END).expect("Cargo.toml has the end marker");
    fs::write(
        &manifest_path,
        format!("{head}{BEGIN}\n{section}\n{END}{tail}"),
    )?;

    println!("wrote {} single-entrypoint targets", wanted.len());
    Ok(())
}
